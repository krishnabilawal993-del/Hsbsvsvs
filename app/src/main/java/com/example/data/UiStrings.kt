    fun get(language: AppLanguage): AppStrings = when (language) {
        AppLanguage.GUJARATI -> gujarati
        AppLanguage.HINDI -> hindi
    }

    fun categoryLabel(category: PortalCategory, language: AppLanguage): String {
        val s = get(language)
        return when (category) {
            PortalCategory.GOVT_JOBS -> s.govtJobsLabel
            PortalCategory.PRIVATE_JOBS -> s.privateJobsLabel
            PortalCategory.SCHOLARSHIPS -> s.scholarshipsLabel
            PortalCategory.COLLEGE_ADMISSIONS -> s.admissionsLabel
            PortalCategory.MERIT_LISTS -> s.meritListsLabel
            PortalCategory.GOVT_SCHEMES -> s.govtSchemesLabel
            PortalCategory.FORM_HELP -> s.formHelpLabel
        }
    }

    fun scholarshipCategoryLabel(cat: ScholarshipCategory, language: AppLanguage): String =
        when (cat) {
            ScholarshipCategory.ALL -> get(language).allLabel
            ScholarshipCategory.ST -> if (language == AppLanguage.GUJARATI) "ST (અનુ. જનજાતિ)" else "ST (अनु. जनजाति)"
            ScholarshipCategory.SC -> if (language == AppLanguage.GUJARATI) "SC (અનુ. જાતિ)" else "SC (अनु. जाति)"
            ScholarshipCategory.OBC -> if (language == AppLanguage.GUJARATI) "OBC / SEBC" else "OBC / SEBC"
            ScholarshipCategory.GENERAL -> if (language == AppLanguage.GUJARATI) "General (બિન અનામત)" else "General (सामान्य)"
        }

    fun admissionStreamLabel(stream: AdmissionStream, language: AppLanguage): String =
        when (stream) {
            AdmissionStream.ALL -> get(language).allLabel
            AdmissionStream.DEGREE_BA_BCOM_BSC -> "BA / BCom / BSc"
